COMPONENTS = 1100
RELATIONS = 70
# Zero-padded so ordinal name order, which the registry binds in, matches numeric order.
lines = ["// Generated by generate.py; do not edit.", "namespace Tralys.Ecs.ManyTypes.Fixture;", ""]
for i in range(COMPONENTS):
    lines.append(f"[Component] public partial struct C{i:04} {{ public int Value; }}")
lines.append("")
for i in range(RELATIONS):
    lines.append(f"[Relation] public partial struct R{i:02};")
open("ManyTypes.g.cs", "w").write("\n".join(lines) + "\n")
